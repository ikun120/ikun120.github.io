/**
 * KasRT - Inventory Feature Logic (Assets, Officers, Teams & Physical Checks)
 * CRUD barang & kategori, pembagian tim berimbang, jadwal, dan pencatatan selisih fisik (adjustments)
 */
(function() {
  'use strict';
  if (window.KasRT_Features_Inventory_Loaded) return;

  const Utils = window.KasRT.Utils;

  const InventoryFeature = {
    async addItem(data) {
      const db = window.KasRT.DB;
      const auth = window.KasRT.Auth;
      const id = db.nextId('INV', 'inventoryItems');
      const item = {
        id,
        nama: data.nama || 'Aset Baru',
        categoryId: data.categoryId || 'INV-CAT-011',
        jumlahBaik: parseInt(data.jumlahBaik, 10) || 0,
        jumlahCacat: parseInt(data.jumlahCacat, 10) || 0,
        keterangan: data.keterangan || '',
        lastCheckedAt: Utils.today(),
        lastCheckedBy: auth?.user?.nama || 'Petugas',
        createdAt: Utils.nowISO(),
        updatedAt: Utils.nowISO()
      };
      await db.set('inventoryItems', item);
      await db.log(auth?.user?.id || 'sys', 'CREATE_INVENTORY_ITEM', 'inventoryItems', id, null, item);
      return item;
    },

    async updateItem(id, patch) {
      const db = window.KasRT.DB;
      const auth = window.KasRT.Auth;
      const old = db.get('inventoryItems', id);
      if (!old) throw new Error('Barang inventaris tidak ditemukan.');
      const updated = await db.update('inventoryItems', id, patch);
      await db.log(auth?.user?.id || 'sys', 'UPDATE_INVENTORY_ITEM', 'inventoryItems', id, old, updated);
      return updated;
    },

    async deleteItem(id) {
      const db = window.KasRT.DB;
      const auth = window.KasRT.Auth;
      const old = db.get('inventoryItems', id);
      if (!old) return false;
      await db.remove('inventoryItems', id);
      await db.log(auth?.user?.id || 'sys', 'DELETE_INVENTORY_ITEM', 'inventoryItems', id, old, null);
      return true;
    },

    async addCategory(data) {
      const db = window.KasRT.DB;
      const id = db.nextId('INV-CAT', 'inventoryCategories');
      const cat = {
        id,
        nama: data.nama,
        deskripsi: data.deskripsi || '',
        icon: data.icon || 'inventory_2',
        warna: data.warna || '#4f46e5',
        urutan: parseInt(data.urutan, 10) || 10,
        aktif: true,
        isDefault: false,
        createdAt: Utils.nowISO(),
        updatedAt: Utils.nowISO()
      };
      await db.set('inventoryCategories', cat);
      return cat;
    },

    async addOfficer(data) {
      const db = window.KasRT.DB;
      const id = db.nextId('INV-OFF', 'inventoryOfficers');
      const officer = {
        id,
        residentId: data.residentId || null,
        nama: data.nama,
        noHp: data.noHp || '',
        alamat: data.alamat || '',
        jabatan: data.jabatan || 'Anggota Tim Aset',
        periodeMulai: data.periodeMulai || Utils.today(),
        periodeSelesai: data.periodeSelesai || `${new Date().getFullYear()}-12-31`,
        status: 'Aktif',
        catatan: data.catatan || '',
        ditunjukOleh: window.KasRT.Auth?.user?.nama || 'Ketua RT',
        ditunjukPada: Utils.nowISO(),
        createdAt: Utils.nowISO(),
        updatedAt: Utils.nowISO()
      };
      await db.set('inventoryOfficers', officer);

      const users = db.list('users');
      const matchedUser = users.find(u => u.residentId === officer.residentId || (u.nama && u.nama.toLowerCase() === officer.nama.toLowerCase()));
      if (matchedUser && !matchedUser.roles.includes('PetugasInventaris')) {
        await db.update('users', matchedUser.id, {
          roles: [...matchedUser.roles, 'PetugasInventaris']
        });
      }
      return officer;
    },

    generateBalancedGroups(officers = [], mode = 'count', value = 2, shuffle = true) {
      let pool = [...officers];
      if (shuffle) {
        pool.sort(() => Math.random() - 0.5);
      }
      const totalOfficers = pool.length;
      if (totalOfficers === 0) return [];
      let groupCount = mode === 'count' ? parseInt(value, 10) : Math.ceil(totalOfficers / parseInt(value, 10));
      groupCount = Math.max(1, Math.min(groupCount, totalOfficers));

      const groups = Array.from({ length: groupCount }, (_, idx) => ({
        id: `INV-GRP-${String(idx + 1).padStart(3, '0')}`,
        nama: `Tim Inventaris ${String.fromCharCode(65 + idx)}`,
        icon: 'diversity_3',
        warna: ['#4f46e5', '#10b981', '#0ea5e9', '#f59e0b', '#ec4899'][idx % 5],
        deskripsi: `Kelompok pemeriksaan aset RT wilayah ${idx + 1}`,
        memberIds: [],
        ketuaId: null,
        status: 'Aktif',
        autoGenerated: true
      }));

      pool.forEach((off, idx) => {
        const targetGroup = groups[idx % groupCount];
        targetGroup.memberIds.push(off.id);
        if (!targetGroup.ketuaId) {
          targetGroup.ketuaId = off.id;
        }
      });

      return groups;
    },

    async finalizeCheck(checkData) {
      const db = window.KasRT.DB;
      const auth = window.KasRT.Auth;
      const checkId = db.nextId('INV-CHK', 'inventoryChecks');
      const now = Utils.nowISO();
      const today = Utils.today();
      const items = checkData.items || [];
      const adjustments = [];
      let totalBaik = 0;
      let totalCacat = 0;
      let hasChanges = false;

      for (const itemInput of items) {
        const originalItem = db.get('inventoryItems', itemInput.itemId);
        if (!originalItem) continue;

        const newBaik = parseInt(itemInput.jumlahBaik, 10) || 0;
        const newCacat = parseInt(itemInput.jumlahCacat, 10) || 0;
        totalBaik += newBaik;
        totalCacat += newCacat;

        const selisihBaik = newBaik - (originalItem.jumlahBaik || 0);
        const selisihCacat = newCacat - (originalItem.jumlahCacat || 0);

        if (selisihBaik !== 0 || selisihCacat !== 0) {
          hasChanges = true;
          const adjId = db.nextId('INV-ADJ', 'inventoryAdjustments');
          const adjDoc = {
            id: adjId,
            itemId: originalItem.id,
            checkId,
            sebelum: { baik: originalItem.jumlahBaik || 0, cacat: originalItem.jumlahCacat || 0 },
            sesudah: { baik: newBaik, cacat: newCacat },
            selisih: { baik: selisihBaik, cacat: selisihCacat },
            alasan: itemInput.catatan || 'Hasil opname fisik berkala',
            petugasNama: checkData.petugasNama || auth?.user?.nama || 'Petugas',
            createdAt: now
          };
          await db.set('inventoryAdjustments', adjDoc);
          adjustments.push(adjDoc);

          await db.update('inventoryItems', originalItem.id, {
            jumlahBaik: newBaik,
            jumlahCacat: newCacat,
            lastCheckedAt: today,
            lastCheckedBy: checkData.petugasNama || auth?.user?.nama || 'Petugas'
          });
        } else {
          await db.update('inventoryItems', originalItem.id, {
            lastCheckedAt: today,
            lastCheckedBy: checkData.petugasNama || auth?.user?.nama || 'Petugas'
          });
        }
      }

      const checkRecord = {
        id: checkId,
        scheduleId: checkData.scheduleId || null,
        tanggalPengecekan: today,
        groupId: checkData.groupId || null,
        groupNama: checkData.groupNama || '',
        petugasNama: checkData.petugasNama || auth?.user?.nama || 'Petugas',
        ringkasan: {
          totalItem: items.length,
          totalBaik,
          totalCacat,
          adaPerubahan: hasChanges
        },
        detailPerubahan: adjustments,
        catatanUmum: checkData.catatanUmum || '',
        status: 'Final',
        createdAt: now
      };

      await db.set('inventoryChecks', checkRecord);

      if (checkData.scheduleId) {
        await db.update('inventorySchedules', checkData.scheduleId, {
          status: 'Selesai',
          lastRunAt: today
        });
      }

      return checkRecord;
    }
  };

  window.KasRT = window.KasRT || {};
  window.KasRT.Features = window.KasRT.Features || {};
  window.KasRT.Features.Inventory = InventoryFeature;
  window.KasRT_Features_Inventory_Loaded = true;
})();
